List<String> _createStatements(
  SchemaSnapshot snapshot,
  SqlDialect dialect,
  Iterable<TableDefinition<Object>> definitions,
) {
  final bindings = {
    for (final d in definitions) (d.schema ?? 'public', d.name): d.columns,
  };
  final inline = dialect == SqlDialect.sqlite;
  return [
    for (final table in snapshot.tables)
      _createTable(
        table,
        dialect,
        bindings[(table.schema ?? 'public', table.name)] ?? const [],
        foreignKeys: inline,
      ),
    for (final table in snapshot.tables)
      for (final index in table.indexes) index.createSqlFor(table, dialect),
    if (!inline)
      for (final table in snapshot.tables)
        for (final column in table.columns)
          if (column.references != null)
            'ALTER TABLE ${dialect.strategy.qualifiedName(table.name, table.schema ?? 'public')} ADD ${_foreignKey(table, column, dialect)}',
  ];
}

String _createTable(
  SchemaTable table,
  SqlDialect dialect,
  Iterable<ColumnDefinition> definitions, {
  required bool foreignKeys,
}) {
  final strategy = dialect.strategy;
  final bindings = {for (final d in definitions) d.name: d};
  final keys = table.columns.where((c) => c.primaryKey).toList();
  final indexed = <String>{
    ...keys.map((c) => c.name),
    for (final c in table.columns)
      if (c.unique || c.references != null) c.name,
    ...table.uniqueConstraints.expand((c) => c.columns),
    ...table.indexes.expand((i) => i.columns),
  };
  if (dialect != SqlDialect.postgres &&
      table.columns.where((c) => c.identity).length > 1) {
    throw const TikalUnsupportedException(
      'Portable tables support only one identity column.',
    );
  }
  final declarations = <String>[];
  for (final column in table.columns) {
    final binding =
        bindings[column.name] ??
        _portableColumn(column, postgres: dialect == SqlDialect.postgres);
    final type = binding.ddlTypeFor(dialect);
    if (dialect == SqlDialect.mysql &&
        indexed.contains(column.name) &&
        RegExp(
          r'^(?:(?:TINY|MEDIUM|LONG)?(?:TEXT|BLOB)|JSON)$',
          caseSensitive: false,
        ).hasMatch(type.trim())) {
      throw TikalUnsupportedException(
        'MySQL index/foreign key on ${table.name}.${column.name} needs an explicitly indexable type, such as @VarChar; implicit prefix lengths are not generated.',
      );
    }
    if (column.identity) {
      final integer = {
        SqlType.smallInteger,
        SqlType.integer,
        SqlType.bigInteger,
      }.contains(binding.sqlType);
      final sqliteKey =
          keys.length == 1 &&
          column.primaryKey &&
          type.toUpperCase() == 'INTEGER';
      final mysqlKey =
          (keys.isNotEmpty && keys.first == column) ||
          column.unique ||
          table.indexes.any((i) => i.columns.first == column.name) ||
          table.uniqueConstraints.any((c) => c.columns.first == column.name);
      if (!integer ||
          dialect == SqlDialect.sqlite && !sqliteKey ||
          dialect == SqlDialect.mysql && !mysqlKey) {
        throw TikalUnsupportedException(
          'Invalid ${dialect.name} identity column ${table.name}.${column.name}.',
        );
      }
    }
    final identity = !column.identity
        ? ''
        : switch (dialect) {
            SqlDialect.postgres => ' GENERATED BY DEFAULT AS IDENTITY',
            SqlDialect.sqlite => ' AUTOINCREMENT',
            SqlDialect.mysql => ' AUTO_INCREMENT',
          };
    final primary = column.primaryKey && keys.length == 1;
    final required = !column.nullable || column.primaryKey;
    final defaultSql = _portableDefault(
      column.defaultSql,
      binding.sqlType,
      type,
      dialect,
    );
    if (column.identity && defaultSql != null) {
      throw TikalUnsupportedException(
        'Identity column ${table.name}.${column.name} cannot also have a default.',
      );
    }
    declarations.add(
      '${strategy.quote(column.name)} $type'
      '${dialect == SqlDialect.sqlite ? '' : identity}'
      '${primary ? ' PRIMARY KEY' : ''}'
      '${dialect == SqlDialect.sqlite ? identity : ''}'
      '${required && !(dialect == SqlDialect.postgres && primary) ? ' NOT NULL' : ''}'
      '${column.unique ? ' UNIQUE' : ''}'
      '${defaultSql == null ? '' : ' DEFAULT $defaultSql'}',
    );
  }
  if (keys.length > 1) {
    declarations.add(
      'PRIMARY KEY (${keys.map((c) => strategy.quote(c.name)).join(', ')})',
    );
  }
  for (final constraint in table.uniqueConstraints) {
    declarations.add(
      'CONSTRAINT ${strategy.quote(constraint.name)} UNIQUE (${constraint.columns.map(strategy.quote).join(', ')})',
    );
  }
  if (foreignKeys) {
    for (final column in table.columns.where((c) => c.references != null)) {
      declarations.add(_foreignKey(table, column, dialect));
    }
  }
  return 'CREATE TABLE ${strategy.qualifiedName(table.name, table.schema ?? 'public')} (${declarations.join(', ')})${dialect == SqlDialect.mysql ? ' ENGINE=InnoDB' : ''}';
}

ColumnDefinition _portableColumn(SchemaColumn column, {bool postgres = false}) {
  final type = column.type.trim().toLowerCase();
  final dimensions = RegExp(
    r'^(varchar|character|numeric)\((\d+)(?:,\s*(\d+))?\)$',
  ).firstMatch(type);
  final base = dimensions?[1] ?? type;
  final sqlType = base == 'varchar'
      ? SqlType.text
      : SqlType.values.where((t) => t.sqlName == base).firstOrNull;
  if (sqlType == null && !postgres) {
    throw TikalUnsupportedException(
      'Cannot infer a portable type from "${column.type}" for ${column.name}; supply its original ColumnDefinition.',
    );
  }
  return ColumnDefinition(
    name: column.name,
    sqlType: sqlType ?? SqlType.text,
    nativeTypes: postgres ? {'postgres': column.type} : const {},
    length: dimensions != null && base != 'numeric'
        ? int.parse(dimensions[2]!)
        : null,
    precision: dimensions != null && base == 'numeric'
        ? int.parse(dimensions[2]!)
        : null,
    scale: dimensions?[3] == null ? null : int.parse(dimensions![3]!),
  );
}

String? _portableDefault(
  String? expression,
  SqlType type,
  String ddl,
  SqlDialect dialect,
) {
  if (expression == null || dialect == SqlDialect.postgres) return expression;
  final sql = expression.trim();
  String literal(String value) =>
      dialect == SqlDialect.mysql &&
          RegExp(
            r'^(?:(?:TINY|MEDIUM|LONG)?(?:TEXT|BLOB)|JSON)$',
            caseSensitive: false,
          ).hasMatch(ddl.trim())
      ? '($value)'
      : value;
  if (type == SqlType.uuid &&
      const {
        'gen_random_uuid()',
        'pg_catalog.gen_random_uuid()',
      }.contains(sql)) {
    return null; // The existing write strategy generates UUIDs on portable engines.
  }
  if (const {'CURRENT_TIMESTAMP', 'CURRENT_DATE'}.contains(sql.toUpperCase())) {
    return dialect == SqlDialect.mysql && sql.toUpperCase() == 'CURRENT_DATE'
        ? '(CURRENT_DATE)'
        : literal(sql.toUpperCase());
  }
  if (sql.toUpperCase() == 'NULL') return 'NULL';
  if (sql.toLowerCase() == 'now()') return literal('CURRENT_TIMESTAMP');
  if (sql.toLowerCase() == 'true' || sql.toLowerCase() == 'false') {
    return literal(sql.toLowerCase() == 'true' ? '1' : '0');
  }
  if (RegExp(r'^[+-]?\d+(?:\.\d+)?(?:[eE][+-]?\d+)?$').hasMatch(sql)) {
    return dialect == SqlDialect.sqlite && type == SqlType.numeric
        ? "'$sql'"
        : literal(sql);
  }
  if (RegExp(r"^'(?:[^']|'')*'$").hasMatch(sql)) {
    final value = sql.substring(1, sql.length - 1).replaceAll("''", "'");
    final escaped = dialect == SqlDialect.mysql
        ? value.replaceAll(r'\', r'\\')
        : value;
    // MySQL 8.0.13+ accepts TEXT/BLOB/JSON defaults as parenthesized expressions.
    return literal("'${escaped.replaceAll("'", "''")}'");
  }
  throw TikalUnsupportedException(
    'Default "$expression" is not portable to ${dialect.name}; use explicit engine DDL.',
  );
}

String _foreignKey(SchemaTable table, SchemaColumn column, SqlDialect dialect) {
  final match = RegExp(
    r'^\s*(?:"((?:[^"]|"")+)"\.)?"((?:[^"]|"")+)"\("((?:[^"]|"")+)"\)(?: ON DELETE (NO ACTION|CASCADE|SET NULL|RESTRICT))?(?: ON UPDATE (NO ACTION|CASCADE|SET NULL|RESTRICT))?\s*$',
  ).firstMatch(column.references!);
  if (match == null) {
    throw TikalUnsupportedException(
      'Cannot translate foreign key ${table.name}.${column.name}.',
    );
  }
  String identifier(int index) => match[index]!.replaceAll('""', '"');
  final name = '${table.name}_${column.name}_fkey';
  validateSchemaIdentifier(name);
  final strategy = dialect.strategy;
  final target = strategy.qualifiedName(
    identifier(2),
    match[1] == null ? null : identifier(1),
  );
  return 'CONSTRAINT ${strategy.quote(name)} FOREIGN KEY (${strategy.quote(column.name)}) REFERENCES $target(${strategy.quote(identifier(3))})'
      '${match[4] == null ? '' : ' ON DELETE ${match[4]}'}'
      '${match[5] == null ? '' : ' ON UPDATE ${match[5]}'}';
}
