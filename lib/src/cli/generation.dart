Future<void> _generateMappings(
  Directory root,
  Map<File, List<AnalyzedModel>> byFile,
  ModelAnalyzer analyzer,
  List<AnalyzedSeeder> seeders,
) async {
  final output = File.fromUri(root.uri.resolve('lib/generated/tikal.dart'));
  const marker = '// GENERATED BY TikalORM - DO NOT MODIFY BY HAND.';
  if (output.existsSync() &&
      !output.readAsStringSync().startsWith('$marker\n')) {
    throw StateError('Refusing to overwrite non-TikalORM file: ${output.path}');
  }
  final code = analyzer.generateLibrary(
    {for (final entry in byFile.entries) entry.key.path: entry.value},
    outputPath: output.path,
    seeders: seeders,
  );
  // Format in memory before touching an existing generated library.
  final formatter = await Process.start(Platform.resolvedExecutable, [
    'format',
    '--output=show',
    '--summary=none',
  ]);
  formatter.stdin.write(code);
  await formatter.stdin.close();
  final streams = await Future.wait([
    formatter.stdout.transform(utf8.decoder).join(),
    formatter.stderr.transform(utf8.decoder).join(),
  ]);
  if (await formatter.exitCode != 0) {
    throw StateError('Generated code formatting failed: ${streams[1]}');
  }
  final formatted = streams[0];
  if (output.existsSync() && output.readAsStringSync() == formatted) {
    stdout.writeln('Unchanged lib/generated/tikal.dart.');
  } else {
    output.parent.createSync(recursive: true);
    output.writeAsStringSync(formatted);
    stdout.writeln(
      'Generated lib/generated/tikal.dart (${byFile.values.fold<int>(0, (count, models) => count + models.length)} models).',
    );
  }
  for (final entry in byFile.entries) {
    final source = entry.key;
    final old = File(
      source.path.replaceFirst(RegExp(r'\.dart$'), '.tikal.dart'),
    );
    if (!old.existsSync()) continue;
    final content = old.readAsStringSync();
    if (analyzer.ownsLegacyOutput(
      content,
      source.uri.pathSegments.last,
      entry.value,
    )) {
      old.deleteSync();
    }
  }
}
