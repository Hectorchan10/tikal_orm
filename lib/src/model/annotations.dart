// Annotations are compile-time input only; no runtime reflection is used.
// Config
import '../config/sql_type.dart';

/// Names the PostgreSQL table represented by a model.
final class TikalTable {
  const TikalTable(this.name, {this.schema});
  final String name;
  final String? schema;
}

/// Overrides a field's column name or PostgreSQL type.
final class Column {
  const Column({this.name, this.type});
  final String? name;
  final SqlType? type;
}

/// Declares the single primary key, optionally a numeric identity.
final class PrimaryKey {
  const PrimaryKey({this.autoIncrement = false});
  final bool autoIncrement;
}

/// Stores a String as PostgreSQL UUID.
final class Uuid {
  const Uuid();
}

/// Stores a String UUID generated by PostgreSQL's gen_random_uuid().
final class UuidGenerated {
  const UuidGenerated();
}

/// Adds a single-column unique constraint.
final class Unique {
  const Unique();
}

/// Limits a String column's length.
final class VarChar {
  const VarChar(this.length);
  final int length;
}

/// Declares a literal SQL default (String, bool, int or finite double).
final class Default {
  const Default(this.value);
  final Object value;
}

/// Enables the repository's creation timestamp support.
final class CreatedAt {
  const CreatedAt();
}

/// Enables the repository's update timestamp support.
final class UpdatedAt {
  const UpdatedAt();
}

/// Declares a foreign key to another annotated model's primary key.
final class ForeignKey {
  const ForeignKey({required this.references});
  final Type references;
}

/// Enables repository soft deletes for this nullable DateTime column.
final class DeletedAt {
  const DeletedAt();
}
